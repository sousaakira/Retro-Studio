import assert from 'node:assert/strict'
import { analyzeMapColors, locateMapColor, colorHex, colorKey, MAX_COLOR_PIXELS, objectPaletteBank, mapPaletteUsage } from '../src/utils/retro/mapColors.js'

const width = 16, height = 8, data = new Uint8ClampedArray(width * height * 4)
// Two separated tiles share red. Transparent RGB values are not palette entries.
data.set([255, 0, 0, 255], 0)
data.set([255, 0, 0, 255], 8 * 4)
data.set([0, 0, 255, 128], 9 * 4)
data.set([42, 123, 10, 0], 10 * 4)
data.set([254, 0, 0, 255], 11 * 4)
const pixels = { width, height, data }, before = data.slice()
const result = analyzeMapColors(pixels)
assert.equal(result.total, 4)
assert.equal(result.colors.length, 3)
assert.deepEqual(result.colors.map(color => color.hex), ['#FF0000', '#0000FF', '#FE0000'])
assert.equal(result.colors[0].count, 2)
assert.equal(colorKey('#ff0000'), 0xff0000)
assert.equal(colorHex(0), '#000000')
assert.equal(colorKey('#xyzxyz'), null)
assert.equal(colorKey('#fff'), null)
const red = locateMapColor(pixels, 0xff0000)
assert.equal(red.count, 2)
assert.deepEqual(red.locations, [{x:0,y:0},{x:8,y:0}])
assert.deepEqual([...red.mask.slice(0,4)], [255,0,0,255])
assert.deepEqual([...red.mask.slice(9*4,10*4)], [0,0,0,205])
assert.equal(red.mask[10*4+3], 0, 'Empty artwork must stay transparent')
assert.equal(locateMapColor(pixels, 0xfe0000).count, 1, 'Close RGB values must not be merged')
assert.equal(locateMapColor(pixels, 0x00ff00).count, 0)
assert.deepEqual(data, before, 'Inspecting colors must not change source artwork')
assert.equal(locateMapColor(pixels,0xff0000,8,true).mask[10*4+3],205,'Isolated sprite inspection dims the surrounding scenery')
assert.equal(objectPaletteBank({properties:{}}),'unknown')
assert.equal(objectPaletteBank({properties:{palette:'2'}}),'2')
assert.equal(objectPaletteBank({properties:{palette:4}}),'unknown')
const usage={tiles:[1,2,0],tiles2:[3,0,4],palette:[0,2,0],palette2:[1,0,3],objects:[{id:1,name:'Hero',visual:{gid:10},properties:{}},{id:2,name:'Enemy',visual:{gid:11},properties:{palette:2}}]}
assert.deepEqual(mapPaletteUsage({...usage,scope:'scenery'}).map(row=>[row.source,row.bank,row.count]),[['BG','0',1],['BG','2',1],['FG','1',1],['FG','3',1]])
assert.deepEqual(mapPaletteUsage({...usage,scope:'sprites',spriteId:'1'}).map(row=>[row.source,row.bank]),[['Hero','unknown']])
assert.throws(()=>analyzeMapColors({width:MAX_COLOR_PIXELS+1,height:1,data:[]}), /tooLarge/)
const many = new Uint8ClampedArray(65537*4)
for (let key=0;key<65537;key++) many.set([key>>>16,(key>>>8)&255,key&255,255],key*4)
assert.throws(()=>analyzeMapColors({width:65537,height:1,data:many}), /tooManyColors/)
console.log('Map colors: exact RGB census, transparency, natural pixels, tile locations, matching mask, immutability and limits passed.')
