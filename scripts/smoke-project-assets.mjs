import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { readGeneratedAssetLedger } from '../electron/retro/generatedAssetLedger.js'
import { writeProjectAsset, assetContentHash } from '../electron/retro/projectAssets.js'
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'retro-asset-'))
try {
  const project = path.join(temporary, 'game')
  fs.mkdirSync(project)
  const bytes = Buffer.from('fixture PNG atlas')
  const filename = 'generated/raster-' + assetContentHash(bytes) + '.png'
  const first = writeProjectAsset(project, 'res', filename, bytes)
  assert.equal(first.reused, false)
  const ledger = readGeneratedAssetLedger(project)
  assert.equal(ledger.assets.length, 1)
  assert.equal(ledger.assets[0].hash, first.hash)
  assert.equal(ledger.assets[0].producer, 'raster-import')
  const output = path.join(project, first.assetPath)
  fs.utimesSync(output, new Date(1000), new Date(1000))
  const before = fs.statSync(output).mtimeMs
  const second = writeProjectAsset(project, 'res', filename, [...bytes])
  assert.equal(second.reused, true)
  assert.equal(fs.statSync(output).mtimeMs, before)
  assert.equal(fs.readdirSync(path.dirname(output)).length, 1)
  assert.throws(() => writeProjectAsset(project, 'res', filename, Buffer.from('different')))
  assert.throws(() => writeProjectAsset(project, 'res', '../outside.png', bytes))
  assert.throws(() => writeProjectAsset(project, '../outside', 'ninja.png', bytes))
  assert.throws(() => writeProjectAsset(project, 'res', 'generated/manual.png', bytes))
  assert.throws(() => writeProjectAsset(project, 'res', 'bad.png', [-1]))
  // #42: importar por bytes nunca troca o conteúdo de um arquivo existente nem acumula cópias.
  const sheet = writeProjectAsset(project, 'res', 'hero.png', Buffer.from('hero v1'))
  assert.deepEqual([sheet.assetPath, sheet.reused, sheet.renamed], [path.join('res', 'hero.png'), false, false])
  assert.deepEqual([writeProjectAsset(project, 'res', 'hero.png', Buffer.from('hero v1')).reused, fs.readdirSync(path.join(project, 'res')).filter(name => name.startsWith('hero')).length], [true, 1])
  const other = writeProjectAsset(project, 'res', 'hero.png', Buffer.from('hero v2'))
  assert.match(other.assetPath, /^res[\\/]hero-[a-f0-9]{8}\.png$/); assert.deepEqual([other.reused, other.renamed], [false, true])
  assert.equal(fs.readFileSync(path.join(project, 'res', 'hero.png'), 'utf8'), 'hero v1', 'o arquivo existente foi preservado')
  for (let i = 0; i < 3; i++) assert.deepEqual([writeProjectAsset(project, 'res', 'hero.png', Buffer.from('hero v2')).assetPath, writeProjectAsset(project, 'res', 'hero.png', Buffer.from('hero v2')).reused], [other.assetPath, true])
  assert.equal(fs.readdirSync(path.join(project, 'res')).filter(name => name.startsWith('hero')).length, 2, 'reimportar não acumulou arquivos')
  // Mesmo conteúdo sob outro nome (arrastar/colar, fundo de mapa): reaproveita o arquivo que já existe.
  const twin = writeProjectAsset(project, 'res', 'copia-do-heroi.png', Buffer.from('hero v1'))
  assert.deepEqual([twin.assetPath, twin.reused, twin.renamed], [path.join('res', 'hero.png'), true, true])
  assert.ok(!fs.existsSync(path.join(project, 'res', 'copia-do-heroi.png')))
  assert.equal(writeProjectAsset(project, 'res', 'hero.gif', Buffer.from('hero v1')).reused, false, 'outra extensão é outro arquivo')
  for (const folder of ['.', '.git/hooks', '.retrostudio']) assert.throws(() => writeProjectAsset(project, folder, 'x.png', Buffer.from('x')), /inside the project/, folder)
  for (const name of ['a"b.png', 'a:b.png', 'a*.png']) assert.throws(() => writeProjectAsset(project, 'res', name, Buffer.from('x')), /Invalid project asset filename/, name)
  fs.symlinkSync(path.join(temporary, 'elsewhere.png'), path.join(project, 'res', 'dangling.png'))
  assert.throws(() => writeProjectAsset(project, 'res', 'dangling.png', Buffer.from('x')), /broken link|symlinked/)
  fs.unlinkSync(path.join(project, 'res', 'dangling.png'))
  const kit = fs.readFileSync(new URL('../src/composables/useTilemapEditorState.js', import.meta.url), 'utf8')
  assert.ok(kit.includes('`map-kit-${stem}-${sourceHash.slice(0, 12)}.png`') && !/map-kit-\$\{stem\}-\$\{id\}/.test(kit), 'mapa em imagem do kit voltou a usar nome com timestamp')
  const outside = path.join(temporary, 'outside')
  fs.mkdirSync(outside)
  fs.symlinkSync(outside, path.join(project, 'escape'))
  assert.throws(() => writeProjectAsset(project, 'escape', 'ninja.png', bytes))
  fs.mkdirSync(path.join(project, 'res', 'directory.png'))
  assert.throws(() => writeProjectAsset(project, 'res', 'directory.png', bytes))
  const normal = writeProjectAsset(project, 'res', 'ninja.png', bytes)
  assert.equal(normal.generated, false)
  assert.equal(readGeneratedAssetLedger(project).assets.length, 1)
  const preexisting = Buffer.from('preexisting generated file')
  const preexistingName = 'generated/raster-' + assetContentHash(preexisting) + '.png'
  fs.writeFileSync(path.join(project, 'res', preexistingName), preexisting)
  assert.equal(writeProjectAsset(project, 'res', preexistingName, preexisting).reused, true)
  assert.equal(readGeneratedAssetLedger(project).assets.length, 1)
  fs.symlinkSync(path.join(project, normal.assetPath), path.join(project, 'res', 'link.png'))
  assert.throws(() => writeProjectAsset(project, 'res', 'link.png', bytes))
  assert.deepEqual(fs.readFileSync(path.join(project, normal.assetPath)), bytes)
  const unicodeBytes = Buffer.from('unicode path atlas')
  writeProjectAsset(project, 'recursos/imágens', 'generated/raster-' + assetContentHash(unicodeBytes) + '.png', unicodeBytes)
  assert.equal(readGeneratedAssetLedger(project).assets.length, 2)
  const ledgerPath = path.join(project, '.retrostudio/generated-assets.json')
  fs.writeFileSync(ledgerPath, '{"version":999,"assets":[]}')
  const rejectedBytes = Buffer.from('rejected on invalid ledger')
  const rejectedName = 'generated/raster-' + assetContentHash(rejectedBytes) + '.png'
  assert.throws(() => writeProjectAsset(project, 'res', rejectedName, rejectedBytes), /Unsupported/)
  assert.ok(!fs.existsSync(path.join(project, 'res', rejectedName)))
  assert.equal(JSON.parse(fs.readFileSync(ledgerPath)).version, 999)
  assert.ok(!fs.readdirSync(path.join(project, 'res')).some(name => name.endsWith('.tmp')))
} finally { fs.rmSync(temporary, { recursive: true, force: true }) }
console.log('Assets: raster por conteúdo, reuso sem regravação, limites e confinamento conferidos.')
