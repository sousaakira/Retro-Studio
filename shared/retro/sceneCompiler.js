// Issue #48: deterministic SGDK scene descriptors; no filesystem or raw C input.
const symbol=/^[A-Za-z_][A-Za-z0-9_]{0,63}$/;
const integer=(value,min,max,label)=>{
 if(!Number.isInteger(value)||value<min||value>max)throw Error('Invalid scene '+label+'.');
 return value;
};
const flag=(value,fallback,label)=>{
 if(value===undefined)return fallback;
 if(typeof value!=='boolean')throw Error('Invalid scene '+label+'.');
 return Number(value);
};
function stableId(value){
 if(Number.isInteger(value))return integer(value,0,65534,'object ID');
 if(typeof value!=='string'||!value.length||value.length>128||/[\u0000-\u001f]/.test(value))throw Error('Invalid scene object ID.');
 let hash=2166136261;
 for(let i=0;i<value.length;i++)hash=Math.imul(hash^value.charCodeAt(i),16777619)>>>0;
 return hash%65535;
}
export function compileScene(scene,{spriteResources=[]}={}){
 if(!scene||typeof scene!=='object'||Array.isArray(scene)||!symbol.test(scene.name||''))throw Error('Invalid scene name.');
 if(Object.hasOwn(scene,'code'))throw Error('Raw scene C is unsupported; existing files preserved.');
 if(!Array.isArray(scene.nodes)||scene.nodes.length>80)throw Error('Scene requires at most 80 objects.');
 const available=new Set(spriteResources),ids=new Set(),sourceIds=new Set();
 const rows=[],durations=[],objects=[];
 for(const node of scene.nodes){
  if(!node||node.type!=='sprite')throw Error('Unsupported scene object type: '+String(node?.type).slice(0,64));
  const id=stableId(node.id);
  if(ids.has(id)||sourceIds.has(String(node.id)))throw Error('Duplicate or colliding scene object ID; assign another ID.');
  ids.add(id);sourceIds.add(String(node.id));
  if(typeof node.resourceId!=='string'||!symbol.test(node.resourceId)||!available.has(node.resourceId))
   throw Error('Missing SPRITE resource for scene object '+String(node.id).slice(0,128));
  const x=integer(node.x??0,-32768,32767,'X'),y=integer(node.y??0,-32768,32767,'Y');
  const sx=integer(node.supportX??0,0,32767,'support X'),sy=integer(node.supportY??0,0,32767,'support Y');
  const animation=integer(node.animation??0,0,32767,'animation');
  const palette=integer(node.palette??1,0,3,'palette');
  const priority=flag(node.priority,0,'priority'),hFlip=flag(node.hFlip,0,'horizontal flip'),
   vFlip=flag(node.vFlip,0,'vertical flip'),loop=flag(node.loop,1,'loop');
  let timing='0',count=0;
  if(node.durations!==undefined){
   if(!Array.isArray(node.durations)||!node.durations.length||node.durations.length>255)throw Error('Invalid scene frame durations.');
   const values=node.durations.map(v=>integer(v,1,65535,'frame duration'));
   timing='scene_'+scene.name+'_timing_'+objects.length;count=values.length;
   durations.push('static const u16 '+timing+'[] = {'+values.join(',')+'};');
  }
  rows.push('    {'+[id,'&'+node.resourceId,x,y,sx,sy,animation,palette,priority,hFlip,vFlip,loop,timing,count].join(',')+'}');
  objects.push({sourceId:node.id,id,resourceId:node.resourceId});
 }
 const prefix='scene_'+scene.name,guard=('RETRO_GENERATED_'+prefix+'_H').toUpperCase(),count=objects.length;
 const header='#ifndef '+guard+'\n#define '+guard+'\n#include "../retro_runtime/retro_scene.h"\n'+
  'extern RetroScene '+prefix+';\nu8 '+prefix+'_init(void);\nvoid '+prefix+'_tick(void);\n'+
  'void '+prefix+'_position(s16 cameraX,s16 cameraY);\nvoid '+prefix+'_free(void);\n#endif\n';
 const source='/* Generated by Retro Studio. Palettes and SPR_update belong to the game host. */\n'+
  '#include "'+prefix+'.h"\n#include "../../res/resources.h"\n'+durations.join('\n')+'\n'+
  (count?'static const RetroSceneObjectDefinition '+prefix+'_definitions[] = {\n'+rows.join(',\n')+'\n};\n':'')+
  'static RetroSceneObject '+prefix+'_objects['+Math.max(1,count)+'];\nRetroScene '+prefix+' = {0};\n'+
  'u8 '+prefix+'_init(void) { return retroSceneInit(&'+prefix+','+prefix+'_objects,'+count+','+
   (count?prefix+'_definitions':'0')+','+count+'); }\n'+
  'void '+prefix+'_tick(void) { retroSceneTick(&'+prefix+'); }\n'+
  'void '+prefix+'_position(s16 x,s16 y) { retroScenePosition(&'+prefix+',x,y); }\n'+
  'void '+prefix+'_free(void) { retroSceneFree(&'+prefix+'); }\n';
 return {source,header,objects,name:scene.name};
}
