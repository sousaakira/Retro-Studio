export const INPUT_ACTIONS = ['left','right','up','down','jump','attack','dash','transform','interact','menu']
export const INPUT_BUTTONS = {UP:1,DOWN:2,LEFT:4,RIGHT:8,B:16,C:32,A:64,START:128,Z:256,Y:512,X:1024,MODE:2048}
export const inputPadMask = pad => pad === 6 ? 4095 : 255
export function createInputConfiguration(pad=3) {
 const make=enabled=>({enabled,pad,bindings:INPUT_ACTIONS.map(id=>({
  id,primary:({left:4,right:8,up:1,down:2,jump:16,attack:64,dash:32,transform:pad===6?1024:34,interact:pad===6?512:1,menu:128})[id],
  alternate:0,exclude:id==='dash'&&pad===3?2:0,bufferFrames:id==='jump'?4:0
 }))})
 return {format:'retro-studio-input',version:1,players:[make(true),make(false)]}
}
export function validateInputConfiguration(config) {
 if(!config||config.format!=='retro-studio-input'||config.version!==1||
  !Array.isArray(config.players)||config.players.length!==2)throw Error('Unsupported input configuration.')
 for(const player of config.players){
  if(typeof player.enabled!=='boolean'||![3,6].includes(player.pad)||
   !Array.isArray(player.bindings)||player.bindings.length!==INPUT_ACTIONS.length)throw Error('Invalid player input configuration.')
  player.bindings.forEach((binding,index)=>{
   if(!binding||binding.id!==INPUT_ACTIONS[index]||
    ['primary','alternate','exclude'].some(key=>!Number.isInteger(binding[key])||binding[key]<0||binding[key]>4095)||
    !Number.isInteger(binding.bufferFrames)||binding.bufferFrames<0||binding.bufferFrames>255)throw Error('Invalid input action binding.')
  })
 }
 return config
}
export function inputWarnings(config) {
 validateInputConfiguration(config)
 const warnings=[]
 config.players.forEach((player,index)=>{
  if(!player.enabled)return
  const mask=inputPadMask(player.pad)
  for(const binding of player.bindings){
   if((binding.primary|binding.alternate|binding.exclude)&~mask)warnings.push({player:index,action:binding.id,kind:'unsupported'})
   if(!binding.primary&&!binding.alternate)warnings.push({player:index,action:binding.id,kind:'unbound'})
  }
 })
 return warnings
}
export function createInputPreviewState(){
 return {held:0,pressed:0,released:0,pending:0,buffered:INPUT_ACTIONS.map(()=>0)}
}
const combination=(mask,buttons,supported)=>!!mask&&!(mask&~supported)&&(buttons&mask)===mask
export function updateInputPreview(state,player,buttons){
 let held=0
 const supported=player.enabled?inputPadMask(player.pad):0
 player.bindings.forEach((binding,index)=>{
  const bit=1<<index
  state.buffered[index]=Math.max(0,state.buffered[index]-1)
  if(!state.buffered[index])state.pending&=~bit
  if(!combination(binding.exclude,buttons,supported)&&
   (combination(binding.primary,buttons,supported)||combination(binding.alternate,buttons,supported)))held|=bit
 })
 state.pressed=held&~state.held;state.released=state.held&~held;state.held=held
 player.bindings.forEach((binding,index)=>{
  if(state.pressed&(1<<index)){state.pending|=1<<index;state.buffered[index]=binding.bufferFrames}
 })
 return state
}
export function consumeInputPreview(state,index){
 if(index<0||index>=INPUT_ACTIONS.length||!(state.pending&(1<<index)))return false
 state.pending&=~(1<<index);state.buffered[index]=0;return true
}
export function compileInputHeader(config){
 validateInputConfiguration(config)
 const rows=config.players.map(player=>' { { '+player.bindings.map(b=>'{'+[b.primary,b.alternate,b.exclude,b.bufferFrames].join(',')+'}').join(',')+' } }')
 return ['/* Generated by Retro Studio. Source: controls/input-map.json */',
 '#ifndef RETRO_STUDIO_INPUT_MAP_H','#define RETRO_STUDIO_INPUT_MAP_H',
 '#include "../retro_runtime/retro_actions.h"',
 'static const RetroActionMap retroProjectInputMaps[2] = {',rows.join(',\n'),'};',
 'static const uint16_t retroProjectInputMasks[2] = {'+config.players.map(p=>p.enabled?inputPadMask(p.pad):0).join(',')+'};',
 '#endif',''].join('\n')
}
